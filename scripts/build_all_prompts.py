#!/usr/bin/env python3
"""Build docs/ALL_PROMPTS.md: every LLM prompt in the system, combined in one document.

Prompt text is pulled straight from the source files (verbatim, via AST), so the
document cannot drift from the code. Re-run after changing any prompt:

    backend/venv/bin/python scripts/build_all_prompts.py

Makes no LLM/API calls.
"""
import ast
import os
import sys
import textwrap

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BACKEND = os.path.join(ROOT, "backend")
sys.path.insert(0, BACKEND)
os.environ.setdefault("GOOGLE_API_KEY", "unused-for-doc-build")

OUT = os.path.join(ROOT, "docs", "ALL_PROMPTS.md")


def source_of(rel_path: str, symbol: str) -> tuple[str, int]:
    """Verbatim source of a top-level def/assign/class, or Class.method. Returns (text, first_line)."""
    path = os.path.join(BACKEND, rel_path)
    src = open(path).read()
    lines = src.splitlines()
    tree = ast.parse(src)

    def seg(n):
        start = min([n.lineno] + [d.lineno for d in getattr(n, "decorator_list", [])])
        return textwrap.dedent("\n".join(lines[start - 1:n.end_lineno])), start

    if "." in symbol:
        cls, meth = symbol.split(".")
        for n in tree.body:
            if isinstance(n, ast.ClassDef) and n.name == cls:
                for m in n.body:
                    if isinstance(m, (ast.FunctionDef, ast.AsyncFunctionDef)) and m.name == meth:
                        return seg(m)
    for n in tree.body:
        if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)) and n.name == symbol:
            return seg(n)
        if isinstance(n, ast.Assign) and any(isinstance(t, ast.Name) and t.id == symbol for t in n.targets):
            return seg(n)
    raise KeyError(f"{symbol} not found in {rel_path}")


out: list[str] = []


def w(s: str = ""):
    out.append(s)


def block(rel_path: str, *symbols: str):
    for sym in symbols:
        text, line = source_of(rel_path, sym)
        w(f"`backend/{rel_path}:{line}` — `{sym}`")
        w()
        w("```python")
        w(text)
        w("```")
        w()


def section(title: str, when: str):
    w(f"### {title}")
    w()
    w(f"**When it runs:** {when}")
    w()


